/**
 * Bundles the Capacitor runtime + plugin proxies into ONE minified ESM file:
 *   <projectRoot>/core/vendor/capacitor.js
 *
 * - no code splitting: the plugins' lazy `import('./web')` web implementations are inlined
 * - target es2020 (iOS 14+ Safari / Android WebView 80+)
 *
 * Usage: node scripts/build-vendor.mjs   (or: npm run vendor)
 */

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import * as esbuild from 'esbuild';
import { PROJECT_ROOT, NATIVE_DIR, isMain } from './paths.mjs';

export const VENDOR_FILE = path.join(PROJECT_ROOT, 'core', 'vendor', 'capacitor.js');

const require = createRequire(import.meta.url);
const versionOf = (pkg) => require(`${pkg}/package.json`).version;

const PACKAGES = [
  '@capacitor/core',
  '@capacitor/filesystem',
  '@capacitor/file-transfer',
  '@capacitor/app',
  '@capacitor/screen-orientation',
  '@capacitor/status-bar',
  '@capacitor/haptics',
  '@capacitor-community/keep-awake',
  '@capgo/capacitor-bluetooth-low-energy',
  'capacitor-tcp-socket',
  '@mhaberler/capacitor-zeroconf-nsd',
];

export async function buildVendor({ quiet = false } = {}) {
  fs.mkdirSync(path.dirname(VENDOR_FILE), { recursive: true });
  const banner =
    '/* Generated by native/scripts/build-vendor.mjs - do not edit.\n' +
    PACKAGES.map((p) => ` * ${p}@${versionOf(p)}`).join('\n') +
    '\n */';

  const result = await esbuild.build({
    entryPoints: [path.join(NATIVE_DIR, 'scripts', 'vendor-entry.js')],
    outfile: VENDOR_FILE,
    absWorkingDir: NATIVE_DIR,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    splitting: false,
    sourcemap: false,
    legalComments: 'eof',
    charset: 'utf8',
    banner: { js: banner },
    metafile: true,
    logLevel: 'warning',
  });

  const code = fs.readFileSync(VENDOR_FILE, 'utf8');
  // Guard: everything must be inlined (no chunks / no runtime imports of other files).
  if (/\bimport\s*\(\s*["'`]/.test(code) || /^\s*import\s/m.test(code)) {
    throw new Error('vendor bundle still contains import statements - inlining failed');
  }
  const inputs = Object.keys(result.metafile.inputs).length;
  if (!quiet) {
    const rel = path.relative(PROJECT_ROOT, VENDOR_FILE).replaceAll('\\', '/');
    console.log(`vendor: ${rel} ${(code.length / 1024).toFixed(1)} KB (${inputs} modules, @capacitor/core ${versionOf('@capacitor/core')})`);
  }
  return { file: VENDOR_FILE, bytes: code.length, inputs };
}

if (isMain(import.meta.url)) {
  await buildVendor();
}
