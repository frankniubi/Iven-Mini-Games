/**
 * Runs the Android Gradle wrapper with the project toolchain (JDK 21 + SDK from ~/dev, proxy flags),
 * without relying on global env vars. Usage: node scripts/gradle.mjs <tasks/args...>
 *   e.g. node scripts/gradle.mjs assembleRelease
 *
 * The wrapper jar is launched with java directly (same command gradlew.bat runs) so no .bat quoting issues.
 * -Dorg.gradle.java.home pins the daemon JDK even if ~/.gradle/gradle.properties sets another one.
 */

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { ANDROID_DIR, isMain } from './paths.mjs';
import { resolveToolchain, gradleSystemProps, toolchainEnv } from './toolchain.mjs';

function ensureLocalProperties(androidHome) {
  const file = path.join(ANDROID_DIR, 'local.properties');
  if (fs.existsSync(file)) return;
  const escaped = androidHome.replace(/\\/g, '\\\\').replace(/:/g, '\\:');
  fs.writeFileSync(file, `# generated by scripts/gradle.mjs (machine-specific, not committed)\nsdk.dir=${escaped}\n`);
}

export function runGradle(args) {
  const tc = resolveToolchain();
  ensureLocalProperties(tc.androidHome);
  const java = path.join(tc.javaHome, 'bin', process.platform === 'win32' ? 'java.exe' : 'java');
  const wrapperJar = path.join(ANDROID_DIR, 'gradle', 'wrapper', 'gradle-wrapper.jar');
  const sysProps = gradleSystemProps(tc);
  const fullArgs = ['-Xmx64m', '-Xms64m', '-Dorg.gradle.appname=gradlew', ...sysProps, '-jar', wrapperJar, ...sysProps, ...args];
  console.log(`> gradle ${args.join(' ')}  (JDK ${tc.javaHome}, SDK ${tc.androidHome}${tc.proxy ? `, proxy ${tc.proxy.url}` : ''})`);
  const res = spawnSync(java, fullArgs, { cwd: ANDROID_DIR, stdio: 'inherit', env: toolchainEnv(tc) });
  if (res.status !== 0) throw new Error(`gradle ${args.join(' ')} failed (exit ${res.status ?? res.signal})`);
}

if (isMain(import.meta.url)) {
  try {
    runGradle(process.argv.slice(2));
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
